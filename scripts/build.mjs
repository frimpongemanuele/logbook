// Build one channel of the app: node scripts/build.mjs beta | live
//   beta → ./beta   (served at /logbook/beta/, own database "logbook-beta", name "JimLogs β")
//   live → ./public (served at /logbook/, database "logbook")
// Promote the tested beta to everyone with: node scripts/build.mjs live
import { execSync } from "child_process";
import fs from "fs"; import path from "path";
const channel = process.argv[2];
if (!["beta", "live"].includes(channel)) { console.error("usage: node scripts/build.mjs beta|live"); process.exit(1); }
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const out = path.join(root, channel === "live" ? "public" : "beta");
const version = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8")).version;
const NAME = channel === "live" ? "JimLogs" : "JimLogs β";
const tsc = fs.existsSync(path.join(root, "node_modules/.bin/tsc")) ? "node_modules/.bin/tsc" : "tsc";
fs.rmSync(path.join(root, ".build"), { recursive: true, force: true });
execSync(`${tsc} -p .`, { cwd: root, stdio: "inherit" });
fs.rmSync(path.join(out, "js"), { recursive: true, force: true });
fs.mkdirSync(path.join(out, "js"), { recursive: true });
const jsFiles = fs.readdirSync(path.join(root, ".build/js")).filter(f => f.endsWith(".js"));
for (const f of jsFiles) fs.copyFileSync(path.join(root, ".build/js", f), path.join(out, "js", f));
fs.writeFileSync(path.join(out, "js/channel.js"), `// generated by scripts/build.mjs\nexport const CHANNEL = "${channel}";\nexport const BUILD_VERSION = "${version}";\n`);
const sub = s => s.replaceAll("{{NAME}}", NAME).replaceAll("{{CHANNEL}}", channel).replaceAll("{{VERSION}}", version);
for (const f of ["index.html", "styles.css", "manifest.webmanifest"]) fs.writeFileSync(path.join(out, f), sub(fs.readFileSync(path.join(root, "web", f), "utf8")));
const shell = ["./", "./index.html", "./styles.css", "./manifest.webmanifest", ...jsFiles.concat(jsFiles.includes("channel.js") ? [] : ["channel.js"]).map(f => "./js/" + f), "./icons/icon-192.png", "./icons/apple-touch-icon.png"];
fs.writeFileSync(path.join(out, "sw.js"), sub(fs.readFileSync(path.join(root, "web/sw.js"), "utf8")).replace("{{SHELL}}", JSON.stringify(shell)));
fs.mkdirSync(path.join(out, "icons"), { recursive: true });
const iconDir = path.join(root, "web", channel === "live" ? "icons" : "icons-beta");
for (const f of fs.readdirSync(iconDir)) fs.copyFileSync(path.join(iconDir, f), path.join(out, "icons", f));
console.log(`built ${channel} ${version} → ${path.relative(root, out)}/ (${jsFiles.length + 1} modules)`);
